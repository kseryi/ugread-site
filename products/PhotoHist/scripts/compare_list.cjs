const missingFromApp = [];
userList.forEach(u => {
  const normU = normalize(u.name);
  const found = appFigures.find(a => normalize(a.name).includes(normU) || normU.includes(normalize(a.name)));
  if (!found) {
    missingFromApp.push(u);
    console.log(`[ВІДСУТНІЙ У ДОДАТКУ]: ${u.name}`);
  } else {
    // console.log(`[Є]: ${u.name} -> ${found.name}`);
  }
});
