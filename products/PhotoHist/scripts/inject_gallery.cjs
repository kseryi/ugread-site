// Load data.js
const code = fs.readFileSync('data.js', 'utf8');

// Parse HISTORICAL_FIGURES from code
const startMarker = 'window.HISTORICAL_FIGURES = [';
const startIndex = code.indexOf(startMarker);
if (startIndex === -1) {
  console.error('Marker not found!');
  process.exit(1);
}

// Evaluate figures by executing in VM or parsing JSON
const vm = require('vm');
const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext(code, sandbox);

const figures = sandbox.window.HISTORICAL_FIGURES;
console.log('Parsed figures count:', figures.length);

let totalAlts = 0;
figures.forEach(fig => {
  const gallery = [
    {
      url: fig.imageUrl,
      label: 'Канонічний портрет ЗНО',
      type: 'Основне зображення',
      caption: 'Офіційний портрет, рекомендований програмою УЦОЯО до ЗНО/НМТ. ' + (fig.visualClues || '')
    }
  ];

  if (ALT_MAP[fig.id]) {
    ALT_MAP[fig.id].forEach(alt => {
      gallery.push(alt);
      totalAlts++;
    });
  }

  fig.gallery = gallery;
});

console.log('Injected gallery across all figures. Total alternative images added:', totalAlts);

// Generate new data.js file
const periodsCode = code.substring(0, startIndex);
const figuresJson = JSON.stringify(figures, null, 2);
const newContent = `${periodsCode}window.HISTORICAL_FIGURES = ${figuresJson};\n`;

fs.writeFileSync('data.js', newContent, 'utf8');
fs.writeFileSync('public/data.js', newContent, 'utf8');

console.log('Successfully updated data.js and public/data.js!');
