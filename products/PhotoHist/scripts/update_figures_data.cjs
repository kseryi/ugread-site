newFigures.forEach(nf => {
  const existingIdx = figures.findIndex(f => f.id === nf.id);
  if (existingIdx !== -1) {
    figures[existingIdx] = nf;
  } else {
    figures.push(nf);
  }
});

// Хронологічне впорядкування за періодами та роками:
const periodOrder = [
  'rus',
  'galicia_volhynia',
  'lithuanian_polish',
  'cossack_war',
  'ruina_mazepa',
  'empires_19th',
  'revolution_unr',
  'interwar_ww2',
  'dissidents_soviet',
  'modern_ukraine'
];

figures.sort((a, b) => {
  const pA = periodOrder.indexOf(a.period);
  const pB = periodOrder.indexOf(b.period);
  if (pA !== pB) return pA - pB;
  return 0;
});

