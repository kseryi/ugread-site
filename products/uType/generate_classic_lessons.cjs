// Запис файлів
let count = 0;
const indexList = [];

lessons.forEach(l => {
  const fileName = `lesson${l.num}.json`;
  const filePath = path.join(outDir, fileName);
  const data = {
    title: l.title,
    text: l.text,
    words: l.words
  };
  fs.writeFileSync(filePath, JSON.stringify(data, null, 2), 'utf8');
  indexList.push({
    id: `classic_${l.num}`,
    num: l.num,
    title: l.title,
    file: `lessons/${fileName}`
  });
  count++;
});

// Додатковий маніфест lessons/index.json для легкої інтеграції в будь-який момент
fs.writeFileSync(
  path.join(outDir, 'index.json'),
  JSON.stringify(indexList, null, 2),
  'utf8'
);

